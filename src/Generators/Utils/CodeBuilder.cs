namespace StolenByte.ValheimX.Generators;

// =============================================================================
internal class CodeBuilder
{
	internal delegate void GenerateAction<T>(CodeBuilder builder, ref readonly T item)
		where T : struct;

	private readonly StringBuilder m_builder;
	private int m_indentLevel;
	private string[] m_indent;

	internal StringBuilder StringBuilder => m_builder;

	public CodeBuilder()
	{
		m_builder = new();
		m_indentLevel = 0;
		m_indent = new string[4];
		RebuildIndent();
	}

	public CodeBuilder Indent()
	{
		m_indentLevel++;
		if (m_indentLevel >= m_indent.Length) {
			var newSize = m_indent.Length * 2;
			Array.Resize(ref m_indent, newSize);
			RebuildIndent(m_indentLevel);
		}
		return this;
	}

	public CodeBuilder Dedent()
	{
		if (m_indentLevel > 0)
			m_indentLevel--;
		return this;
	}

	public void Reset()
	{
		m_builder.Clear();
		m_indentLevel = 0;
	}

	public CodeBuilder Append<T>(T value)
	{
		m_builder.Append(value);
		return this;
	}

	public CodeBuilder AppendFormat(string format, params object[] args)
	{
		m_builder.AppendFormat(format, args);
		return this;
	}

	public CodeBuilder AppendItems(string sep, IEnumerable<string> items)
	{
		foreach (var item in items.Intersperse(sep))
			m_builder.Append(item);
		return this;
	}

	public CodeBuilder AppendItems(string sep, params string[] items)
		=> AppendItems(sep, items.AsEnumerable());

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginLine()
		=> AppendIndent();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginLine(string text)
		=> BeginLine().Append(text);

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder EndLine()
		=> AppendNewLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder EndLine(string text)
		=> Append(text).EndLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Line()
		=> AppendNewLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Line(string text)
		=> BeginLine().Append(text).EndLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder LineF(string format, params object[] args)
		=> BeginLine().AppendFormat(format, args).EndLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginStatement()
		=> BeginLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginStatement(string text)
		=> BeginLine(text);

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder EndStatement()
		=> Append(';').EndLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder EndStatement(string text)
		=> Append(text).EndStatement();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Statement(string text)
		=> BeginStatement().Append(text).EndStatement();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder StatementF(string format, params object[] args)
		=> BeginStatement().AppendFormat(format, args).EndStatement();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginBlock()
	{
		if (IsNewLine())
			AppendIndent();
		return Append('{').EndLine().Indent();
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginBlock(string text)
	{
		if (IsNewLine())
			AppendIndent();
		return Append(text).Append(' ').Append('{').EndLine().Indent();
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder EndBlock(bool newLine = true)
	{
		Dedent().BeginLine().Append('}');
		return newLine ? EndLine() : Append(' ');
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Comment(string text)
		=> BeginLine("// ").Append(text).EndLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder CommentF(string format, params object[] args)
		=> BeginLine("// ").AppendFormat(format, args).EndLine();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Header()
		=> Comment("<auto-generated />").Line("#nullable enable");

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Namespace(string? name)
	{
		if (name is not null)
			StatementF("namespace {0}", name);
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Usings(params string[] names)
	{
		foreach (var name in names)
			StatementF("using {0}", name);
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginClass(
		Accessibility vis,
		string name,
		bool isStatic = false,
		bool isPartial = true)
	{
		BeginLine(SyntaxFacts.GetText(vis)).Append(' ');
		if (isStatic)
			Append("static ");
		if (isPartial)
			Append("partial ");
		return Append("class ").Append(name).AppendNewLine().BeginBlock();
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder EndClass()
		=> EndBlock();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginFunction(Accessibility vis, string signature)
		=> BeginLine(SyntaxFacts.GetText(vis))
				.Append(' ')
				.Append(signature)
				.AppendNewLine()
				.BeginBlock();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder BeginFunctionF(Accessibility vis, string format, params string[] args)
		=> BeginLine(SyntaxFacts.GetText(vis))
				.Append(' ')
				.AppendFormat(format, args)
				.AppendNewLine()
				.BeginBlock();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder EndFunction()
		=> EndBlock();

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Property(
		Accessibility vis,
		string type,
		string name,
		bool read = true,
		bool write = true,
		bool init = false,
		string? value = null)
	{
		BeginStatement(SyntaxFacts.GetText(vis))
			.Append(' ')
			.Append(type)
			.Append(' ')
			.Append(name)
			.Append(" { ");

		if (read)
			Append("get; ");
		if (init)
			Append("init; ");
		else if (write)
			Append("set; ");

		Append('}');

		if (value is not null)
			Append(" = ").Append(value);

		return EndStatement();
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Property(
		Accessibility vis,
		ITypeSymbol type,
		string name,
		bool read = true,
		bool write = true,
		bool init = false,
		string? value = null)
		=> Property(vis, type.ToDisplayString(), name, read, write, init, value);

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Field(
		Accessibility vis,
		string type,
		string name,
		bool isConst = false,
		bool readOnly = false,
		bool required = false,
		string? value = null)
	{
		BeginStatement(SyntaxFacts.GetText(vis)).Append(' ');
		if (isConst)
			Append("const ");
		else if (readOnly)
			Append("readonly ");
		else if (required)
			Append("required ");

		Append(type).Append(' ').Append(name);
		if (value is not null)
			Append(" = ").Append(value);

		return EndStatement();
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder Field(
		Accessibility vis,
		ITypeSymbol type,
		string name,
		bool isConst = false,
		bool readOnly = false,
		bool required = false,
		string? value = null)
		=> Field(vis, type.ToDisplayString(), name, isConst, readOnly, required, value);

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder With(Action<CodeBuilder> action)
	{
		action(this);
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder With<T>(T arg, Action<CodeBuilder, T> action)
	{
		action(this, arg);
		return this;
	}

	[MethodImpl(MethodImplOptions.AggressiveInlining)]
	public CodeBuilder With<T>(ref readonly T arg, GenerateAction<T> action)
		where T : struct
	{
		action(this, in arg);
		return this;
	}

	public CodeBuilder For<T>(IEnumerable<T> items, Action<CodeBuilder, T> action)
	{
		foreach (var arg in items)
			action(this, arg);
		return this;
	}

	public CodeBuilder For<T>(ReadOnlySpan<T> items, GenerateAction<T> action)
		where T : struct
	{
		foreach (ref readonly var item in items) {
			action(this, in item);
		}
		return this;
	}

	public CodeBuilder IfNotNull<T>(ref readonly T? arg, GenerateAction<T> action, Action<CodeBuilder>? nullAction = null)
		where T : struct
	{
		if (arg is T value)
			action(this, in value);
		else if (nullAction is not null)
			nullAction(this);
		return this;
	}

	public CodeBuilder IfNotNull<T>(T? arg, Action<CodeBuilder, T> action, Action<CodeBuilder>? nullAction = null)
		where T : struct
	{
		if (arg is T value)
			action(this, value);
		else if (nullAction is not null)
			nullAction(this);
		return this;
	}

	// duplicated with different constraint because C# generics are stupid,
	// and this is the only way we can get proper nullability typing on `action`s `T` parameter
	public CodeBuilder IfNotNull<T>(T? arg, Action<CodeBuilder, T> action, Action<CodeBuilder>? nullAction = null)
		where T : class
	{
		if (arg is not null)
			action(this, arg);
		else if (nullAction is not null)
			nullAction(this);
		return this;
	}

	public override string ToString()
	{
		var result = m_builder.ToString();
		Reset();
		return result;
	}

	CodeBuilder AppendNewLine()
	{
		m_builder.AppendLine();
		return this;
	}

	CodeBuilder AppendIndent()
	{
		m_builder.Append(m_indent[m_indentLevel]);
		return this;
	}

	bool IsNewLine()
		=> m_builder.EndsWith('\r', '\n');

	void RebuildIndent(int @from = 0)
	{
		if (@from == 0) {
			m_indent[0] = string.Empty;
			m_indent[1] = "\t";
			@from += 2;
		}

		for (var i = @from; i < m_indent.Length; ++i) {
			m_indent[i] = m_indent[i - 1] + "\t";
		}
	}
}
